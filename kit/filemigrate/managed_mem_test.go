// TestMemManagedSourceStore_NegativeLimitRejected verifies that a negative
// field in ResourceLimits is rejected with ErrInvalidConfig before any size
// comparison runs, so that managed-source-store error semantics match the
// other public stores (MemArtifactStore, FSArtifactStore, MemSourceStore,
// FSSourceStore) instead of silently returning ErrResourceLimit after a
// comparison against a negative value.
func TestMemManagedSourceStore_NegativeLimitRejected(t *testing.T) {
	store := filemigrate.NewMemManagedSourceStore()
	root, err := store.ResolveSourceRoot(t.Context(), "/out")
	if err != nil {
		t.Fatal(err)
	}

	const header = "// Code generated by Grizzle. DO NOT EDIT.\n"
	cases := []struct {
		name   string
		limits filemigrate.ResourceLimits
	}{
		{"MaxRenderedSourceFileBytes", filemigrate.ResourceLimits{MaxRenderedSourceFileBytes: -1}},
		{"MaxRenderedSourceBytes", filemigrate.ResourceLimits{MaxRenderedSourceBytes: -1}},
		{"MaxSchemaFiles", filemigrate.ResourceLimits{MaxSchemaFiles: -1}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := store.WriteManagedFile(t.Context(), root, "users.go",
				[]byte(header+"package schema\n"),
				filemigrate.ManagedWriteOptions{Header: header, Limits: tc.limits})
			if !errors.Is(err, filemigrate.ErrInvalidConfig) {
				t.Errorf("expected ErrInvalidConfig, got %v", err)
			}
		})
	}
}

