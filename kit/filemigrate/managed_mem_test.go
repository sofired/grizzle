func TestMemManagedSourceStore_EmptyDirRejected(t *testing.T) {
	store := filemigrate.NewMemManagedSourceStore()
	_, err := store.ResolveSourceRoot(t.Context(), "")
	if err == nil {
		t.Fatal("expected error for empty dir")
	}
	if !errors.Is(err, filemigrate.ErrInvalidConfig) {
		t.Errorf("expected ErrInvalidConfig, got %v", err)
	}
}

func TestMemManagedSourceStore_ResolveSucceeds(t *testing.T) {
	store := filemigrate.NewMemManagedSourceStore()
	root, err := store.ResolveSourceRoot(t.Context(), "/out")
	if err != nil {
		t.Fatalf("ResolveSourceRoot: %v", err)
	}
	if root.RealPath != "/out" {
		t.Errorf("RealPath = %q, want %q", root.RealPath, "/out")
	}
}

func TestMemManagedSourceStore_WriteAndReadBack(t *testing.T) {
	store := filemigrate.NewMemManagedSourceStore()
	root, err := store.ResolveSourceRoot(t.Context(), "/out")
	if err != nil {
		t.Fatal(err)
	}

	const header = "// Code generated by Grizzle. DO NOT EDIT.\n"
	content := []byte(header + "package schema\n")

	mf, err := store.WriteManagedFile(t.Context(), root, "users.go", content, filemigrate.ManagedWriteOptions{
		Header: header,
	})
	if err != nil {
		t.Fatalf("WriteManagedFile: %v", err)
	}
	if mf.RelPath != "users.go" {
		t.Errorf("RelPath = %q, want %q", mf.RelPath, "users.go")
	}
	if !mf.Written {
		t.Error("Written should be true for a new file")
	}
	var zero filemigrate.Digest
	if mf.ContentSHA256 == zero {
		t.Error("ContentSHA256 must not be zero")
	}
}

func TestMemManagedSourceStore_OverwriteOwnedFileSucceeds(t *testing.T) {
	store := filemigrate.NewMemManagedSourceStore()
	root, _ := store.ResolveSourceRoot(t.Context(), "/out")

	const header = "// Code generated by Grizzle. DO NOT EDIT.\n"
	first := []byte(header + "package schema // v1\n")
	second := []byte(header + "package schema // v2\n")

	if _, err := store.WriteManagedFile(t.Context(), root, "users.go", first, filemigrate.ManagedWriteOptions{Header: header}); err != nil {
		t.Fatalf("first write: %v", err)
	}
	mf, err := store.WriteManagedFile(t.Context(), root, "users.go", second, filemigrate.ManagedWriteOptions{Header: header})
	if err != nil {
		t.Fatalf("second write: %v", err)
	}
	if !mf.Written {
		t.Error("Written should be true when content changed")
	}
}

