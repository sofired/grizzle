func TestMemManagedSourceStore_NoFollowContainment(t *testing.T) {
	store := filemigrate.NewMemManagedSourceStore()
	root, _ := store.ResolveSourceRoot(t.Context(), "/out")

	// Write to different roots; the store must not mix them up.
	const header = "// Code generated by Grizzle. DO NOT EDIT.\n"
	content := []byte(header + "package a\n")
	if _, err := store.WriteManagedFile(t.Context(), root, "a.go", content, filemigrate.ManagedWriteOptions{Header: header}); err != nil {
		t.Fatalf("WriteManagedFile: %v", err)
	}

	// A different root must not see the file.
	otherRoot, _ := store.ResolveSourceRoot(t.Context(), "/other")
	mf, err := store.WriteManagedFile(t.Context(), otherRoot, "a.go", content, filemigrate.ManagedWriteOptions{Header: header})
	if err != nil {
		t.Fatalf("WriteManagedFile on other root: %v", err)
	}
	// File did not exist under /other, so Written must be true.
	if !mf.Written {
		t.Error("Written should be true: file was not present under the other root")
	}
}
